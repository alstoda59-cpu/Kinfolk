assert.match(handler,/count!==1\|\|!album\?\.id\|\|album\.owner_id!==uid/,'album acknowledgment owner checked');
assert.match(handler,/if\(!active\(\)\)return;\s*const f=files\[i\]/,'upload loop guarded');

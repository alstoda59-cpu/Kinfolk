import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';

const sql=readFileSync(new URL('../migrations/ALPHA_only_stories_rls.sql',import.meta.url),'utf8');
const html=readFileSync(new URL('../index.html',import.meta.url),'utf8');
const norm=s=>s.replace(/\\s+/g,' ').toLowerCase();

test('Recovery415 migration is explicitly restricted to the isolated alpha project',()=>{
  assert.match(sql,/viantpfagtbgyyzavmtv/);
  assert.match(sql,/NEVER run on shared\/live zojajuzmfjpvubzibzgg/);
  assert.match(sql,/create table public\.kinfolk_stories/i);
});
test('story schema matches the real mobile create/load/view handlers',()=>{
  for(const column of ['id','owner_id','body','media_url','created_at','expires_at'])
    assert.match(sql,new RegExp('\\\\b'+column+'\\\\b','i'));
  assert.match(html,/sb\.from\('kinfolk_stories'\)\.insert\(\{owner_id:uid,body,media_url:path\}/);
  assert.match(html,/sb\.from\('kinfolk_stories'\)\.select\('\*'\)\.gt\('expires_at'/);
});
test('story expiry is generated by database and cannot be overridden by clients',()=>{
  assert.match(norm(sql),/expires_at timestamptz not null default \(now\(\)\+interval '24 hours'\)/);
  assert.match(norm(sql),/expires_at>created_at and expires_at<=created_at\+interval '24 hours'/);
  assert.match(norm(sql),/grant insert\(owner_id,body,media_url\) on public\.kinfolk_stories to authenticated/);
  assert.doesNotMatch(norm(sql),/grant (?:all|insert,update|update) on public\.kinfolk_stories to authenticated/);
});
test('story metadata rejects forged storage ownership paths and empty content',()=>{
  assert.match(sql,/kinfolk_stories_media_owner_path/);
  assert.match(sql,/owner_id::text\|\| '\/stories\/'/);
  assert.match(sql,/kinfolk_stories_nonempty/);
  assert.match(sql,/char_length\(body\)<=2000/);
});
test('story RLS is enabled and anonymous grants are revoked',()=>{
  assert.match(norm(sql),/alter table public\.kinfolk_stories enable row level security/);
  assert.match(norm(sql),/revoke all on public\.kinfolk_stories from public,anon,authenticated/);
  assert.match(norm(sql),/for select to authenticated/);
  assert.match(norm(sql),/for insert to authenticated/);
  assert.match(norm(sql),/for delete to authenticated/);
});
test('story read requires unexpired parent, public profile or owner, and reciprocal block guard',()=>{
  assert.match(sql,/expires_at>now\(\)/);
  assert.match(sql,/owner_id=\(select auth\.uid\(\)\)/);
  assert.match(sql,/kinfolk_alpha_private\.not_blocked\(owner_id\)/);
  assert.match(sql,/p\.id=owner_id and p\.is_private=false/);
});
test('story write/delete policies restrict authenticated identity',()=>{
  assert.match(norm(sql),/for insert to authenticated with check \(owner_id=\(select auth\.uid\(\)\)\)/);
  assert.match(norm(sql),/for delete to authenticated using \(owner_id=\(select auth\.uid\(\)\)\)/);
});
test('story media read is tied to visible unexpired parent in private media bucket',()=>{
  assert.match(sql,/on storage\.objects for select to authenticated/);
  assert.match(sql,/bucket_id='kinfolk-media'/);
  assert.match(sql,/\(storage\.foldername\(name\)\)\[2\]='stories'/);
  assert.match(sql,/from public\.kinfolk_stories s/);
  assert.match(sql,/s\.media_url=storage\.objects\.name and s\.expires_at>now\(\)/);
  assert.doesNotMatch(sql,/update storage\.buckets|public\s*=\s*true/i);
});
